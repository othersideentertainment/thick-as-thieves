{
   ATATWorldMapBoundary* newMapBoundary = _registeredMaps.IsValidIndex(newIndex) ? _registeredMaps[newIndex].BoundaryActor.Get() : nullptr;
   OnActiveMapChanged.Broadcast(newIndex, newMapBoundary);
}

