{
}

TSoftObjectPtr<UTextureRenderTarget2D> UTATWorldMapSubsystem::GetRenderTargetForAutoGeneratedMap(ATATWorldMapBoundary* mapBoundaryActor)
{
   if (mapBoundaryActor == nullptr)
   {
      return {};
   }

   const int32 mapIndex = _FindRegisteredMapIndex(mapBoundaryActor);
   if (mapIndex == INDEX_NONE)
   {
      return {};
   }

   FRegisteredMap& thisMap = _registeredMaps[mapIndex];
   if (thisMap.IsPrimary)
   {
      return UTATProjectSettings::Get().AutoGeneratedMapRenderTarget;
   }

   const TArray<TSoftObjectPtr<UTextureRenderTarget2D>>& allSecondaryRenderTargets = UTATProjectSettings::Get().AutoGeneratedMapRenderTargets_Secondary;

   // Try and assign a render target asset to this map boundary if we don't already have one
   if (thisMap.RenderTargetIndex == INDEX_NONE)
   {
      int32 maxAssignedRenderTargetIndex = INDEX_NONE;
      for (const FRegisteredMap& map : _registeredMaps)
      {
         if (!map.IsPrimary && map.RenderTargetIndex != INDEX_NONE)
         {
            maxAssignedRenderTargetIndex = FMath::Max(maxAssignedRenderTargetIndex, map.RenderTargetIndex);
         }
      }

      const int32 nextRenderTargetIndex = maxAssignedRenderTargetIndex + 1;
      if (allSecondaryRenderTargets.IsValidIndex(nextRenderTargetIndex))
      {
         thisMap.RenderTargetIndex = nextRenderTargetIndex;
      }
   }

   return (thisMap.RenderTargetIndex != INDEX_NONE)
      ? allSecondaryRenderTargets[thisMap.RenderTargetIndex]
      : TSoftObjectPtr<UTextureRenderTarget2D>{};
}

void UTATWorldMapSubsystem::NotifyLocalPlayerInteriorMapBeginOverlap(ATATWorldMapBoundary* mapBoundary, ATATPlayerController* pc)
{
   if (!ensure(mapBoundary) || mapBoundary == _GetCurrentWorldMapBoundaryActor())
   {
      return;
   }

   // Automatically fire OnActiveMapChanged event at the end of this function if any change occured
   FActiveMapChangeTracker activeMapChangeTracker{ this };

   const int32 newMapIndex = _FindRegisteredMapIndex(mapBoundary);
   if (newMapIndex != INDEX_NONE)
   {
      _activeMapStack.Add(newMapIndex);
   }
}

void UTATWorldMapSubsystem::NotifyLocalPlayerInteriorMapEndOverlap(ATATWorldMapBoundary* mapBoundary, ATATPlayerController* pc)
{
   if (!ensure(mapBoundary))
   {
      return;
   }

   const int32 thisMapIndex = _FindRegisteredMapIndex(mapBoundary);
   if (thisMapIndex == INDEX_NONE)
   {
      UE_LOG(LogTATWorldMapSubsystem, Error, TEXT("Got EndOverlap event for unknown map boundary actor %s"), *GetNameSafe(mapBoundary));
      return;
   }

   // Automatically fire OnActiveMapChanged event at the end of this function if any change occured
   FActiveMapChangeTracker activeMapChangeTracker{ this };

   _activeMapStack.RemoveAll([thisMapIndex](int32 idx) { return idx == thisMapIndex; });
}

int32 UTATWorldMapSubsystem::_FindRegisteredMapIndex(ATATWorldMapBoundary* mapBoundary) const
{
   if (mapBoundary != nullptr)
   {
      for (int32 i = 0; i < _registeredMaps.Num(); i++)
      {
         ATATWorldMapBoundary* thisMap = _registeredMaps[i].BoundaryActor.Get();
         if (thisMap == mapBoundary)
         {
            return i;
         }
      }
   }
   return INDEX_NONE;
}

ATATWorldMapBoundary* UTATWorldMapSubsystem::_GetCurrentWorldMapBoundaryActor(int32* outIndex) const
{
   const int32 idx = GetCurrentMapIndex();
   if (_registeredMaps.IsValidIndex(idx))
   {
      if (outIndex != nullptr)
      {
         *outIndex = idx;
      }
      return _registeredMaps[idx].BoundaryActor.Get();
   }

   if (outIndex != nullptr)
   {
      *outIndex = INDEX_NONE;
   }
   return nullptr;
}

