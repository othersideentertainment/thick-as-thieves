bool UTATWorldMapSubsystem::ShouldCreateSubsystem(UObject* outer) const
{
   if (!Super::ShouldCreateSubsystem(outer))
   {
      return false;
   }

   if (const UWorld* world = outer->GetWorld())
   {
      if (!world->IsGameWorld())
      {
         return false;
      }

      if (const UGameInstance* gameInstance = world->GetGameInstance())
      {
         if (gameInstance->IsDedicatedServerInstance())
         {
            return false;
         }
      }
   }

   return true;
}

int32 UTATWorldMapSubsystem::GetNumMaps() const
{
   return _registeredMaps.Num();
}

ATATWorldMapBoundary* UTATWorldMapSubsystem::GetMapBoundaryActor(int32 mapIndex) const
{
   return _registeredMaps.IsValidIndex(mapIndex) ? _registeredMaps[mapIndex].BoundaryActor.Get() : nullptr;
}

