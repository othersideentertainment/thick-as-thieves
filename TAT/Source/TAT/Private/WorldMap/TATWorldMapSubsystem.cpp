{
   return _GetCurrentWorldMapBoundaryActor();
}

FText UTATWorldMapSubsystem::GetMapLabel(int32 mapIndex) const
{
   return _registeredMaps.IsValidIndex(mapIndex) ? _registeredMaps[mapIndex].Label : FText::GetEmpty();
}

int32 UTATWorldMapSubsystem::GetCurrentMapIndex() const
{
   return (_activeMapIndexOverride != INDEX_NONE) ? _activeMapIndexOverride : GetMapIndexForCurrentPlayerLocation();
}

int32 UTATWorldMapSubsystem::GetMapIndexForCurrentPlayerLocation() const
{
   return !_activeMapStack.IsEmpty() ? _activeMapStack.Last() : _primaryMapIndex;
}

bool UTATWorldMapSubsystem::GetMapIndexOverride(int32& overrideIndex) const
{
   overrideIndex = _activeMapIndexOverride;
   return overrideIndex != INDEX_NONE;
}

void UTATWorldMapSubsystem::SetMapIndexOverride(int32 newIndex)
{
   // Automatically fire OnActiveMapChanged event at the end of this function if any change occured
   FActiveMapChangeTracker activeMapChangeTracker{ this };

   _activeMapIndexOverride = FMath::Clamp(newIndex, -1, _registeredMaps.Num() - 1);
}

void UTATWorldMapSubsystem::ClearMapIndexOverride()
{
   // Automatically fire OnActiveMapChanged event at the end of this function if any change occured
   FActiveMapChangeTracker activeMapChangeTracker{ this };

   _activeMapIndexOverride = INDEX_NONE;
}

void UTATWorldMapSubsystem::InitAutoSelectedMap(FVector playerLocation)
{
   // Automatically fire OnActiveMapChanged event at the end of this function if any change occured
   FActiveMapChangeTracker activeMapChangeTracker{ this };

   // Assume the map boundaries aren't overlapping (much) and just select the where the player is closest to the center.
   // Ideally we could just pick the first box that overlaps the player, but I want to make sure two slightly overlapping map boundaries
   // (eg. two floors of a building) don't cause issues.
   // Not the best heuristic but it's probably fine for now.
   float bestDistSquared = std::numeric_limits<float>::max();
   int32 bestMapIndex = INDEX_NONE;
   for (int32 i = 0; i < _registeredMaps.Num(); i++)
   {
      const FRegisteredMap& map = _registeredMaps[i];
      if (map.IsPrimary || !map.Bounds.IsInside(playerLocation))
      {
         continue;
      }

      ATATWorldMapBoundary* mapBoundaryActor =  map.BoundaryActor.Get();
      if (mapBoundaryActor == nullptr || !mapBoundaryActor->AutoSwitchToMap)
      {
         continue;
      }

      const float distSq = FVector::DistSquared(map.Bounds.GetCenter(), playerLocation);
      if (distSq < bestDistSquared)
      {
         bestDistSquared = distSq;
         bestMapIndex = i;
      }
   }

   if (_registeredMaps.IsValidIndex(bestMapIndex))
   {
      _activeMapStack.SetNum(1);
      _activeMapStack[0] = bestMapIndex;
   }
   else
   {
      _activeMapStack.Empty();
   }
}

bool UTATWorldMapSubsystem::GetWorldMapMaterialAndAnchors(TSoftObjectPtr<UTexture2D>& texture, TSoftObjectPtr<UMaterialInterface>& material, FVector2D& anchorTopLeft, FVector2D& anchorBottomRight, bool& isAutoGenerated) const
{
   texture.Reset();
   material.Reset();
   anchorTopLeft = FVector2D(0, 0);
   anchorBottomRight = FVector2D(2048, 2048);
   isAutoGenerated = false;

   if (ATATWorldMapBoundary* worldMapBoundary = _GetCurrentWorldMapBoundaryActor())
   {
      texture = worldMapBoundary->MapTexture;
      material = worldMapBoundary->GetMapMaterial();
      worldMapBoundary->GetMapTextureAnchorPoints(anchorTopLeft, anchorBottomRight);
      isAutoGenerated = worldMapBoundary->UseAutoGeneratedMap();
      return true;
   }

   return false;
}

UTexture* UTATWorldMapSubsystem::GetAutoGeneratedWorldMapTexture(bool forceUpdate)
{
   ATATWorldMapBoundary* worldMapBoundary = _GetCurrentWorldMapBoundaryActor();
   return (worldMapBoundary != nullptr)
      ? worldMapBoundary->GetAutoGeneratedMapTexture(forceUpdate)
      : nullptr;
}

bool UTATWorldMapSubsystem::GetMapInfo(FTATActiveMapInfo& mapInfo, int32 mapIndex, bool forceUpdateIfAutoGenerated)
{
   mapInfo = FTATActiveMapInfo{};

   const FRegisteredMap* registeredMap = nullptr;
   if (mapIndex == -1)
   {
      mapIndex = GetCurrentMapIndex();
   }

   if (_registeredMaps.IsValidIndex(mapIndex))
   {
      registeredMap = &_registeredMaps[mapIndex];
   }

   if (registeredMap != nullptr)
   {
      mapInfo.MapBoundary = registeredMap->BoundaryActor.Get();
      mapInfo.Label = registeredMap->Label;
      if (mapInfo.MapBoundary != nullptr)
      {
         mapInfo.Texture = mapInfo.MapBoundary->MapTexture;
         mapInfo.Material = mapInfo.MapBoundary->GetMapMaterial();
         mapInfo.MapBoundary->GetMapTextureAnchorPoints(mapInfo.AnchorTopLeft, mapInfo.AnchorBottomRight);
         mapInfo.IsAutoGenerated = mapInfo.MapBoundary->UseAutoGeneratedMap();
         if (mapInfo.IsAutoGenerated)
         {
            mapInfo.AutoGeneratedTexture = mapInfo.MapBoundary->GetAutoGeneratedMapTexture(forceUpdateIfAutoGenerated);
         }
      }
      return true;
   }

   return false;
}

void UTATWorldMapSubsystem::RegisterMapActor(UTATMapActorComponent* mapActorComponent)
{
   check(IsValid(mapActorComponent));
   check(!GetWorld()->GetGameInstance()->IsDedicatedServerInstance());

   bool alreadyInSet = false;
   _mapRepresentedActors.Add(mapActorComponent, &alreadyInSet);
   if (alreadyInSet)
   {
      UE_LOG(LogTATWorldMapSubsystem, Warning, TEXT("RegisterMapActor() called with previously-registered UTATMapActorComponent %s (owner = %s)!")
         , *mapActorComponent->GetName()
         , *mapActorComponent->GetOwner()->GetName());
      return;
   }

   OnMapActorRegistered.Broadcast(mapActorComponent);

   UE_LOG(LogTATWorldMapSubsystem, Verbose, TEXT("Registered map actor %s"), *mapActorComponent->GetOwner()->GetName());
}

void UTATWorldMapSubsystem::UnregisterMapActor(UTATMapActorComponent* mapActorComponent)
{
   check(IsValid(mapActorComponent));

   check(!GetWorld()->GetGameInstance()->IsDedicatedServerInstance());

   if (_mapRepresentedActors.Remove(mapActorComponent) > 0)
   {
      OnMapActorUnregistered.Broadcast(mapActorComponent);
      UE_LOG(LogTATWorldMapSubsystem, Verbose, TEXT("Unregistered map actor %s"), *mapActorComponent->GetOwner()->GetName());
   }
}

void UTATWorldMapSubsystem::UnregisterAllMapActorsWithSpriteTag(const FGameplayTag spriteTag)
{
   TArray<UTATMapActorComponent*> mapActorsToRemove;

   for (TWeakObjectPtr<UTATMapActorComponent> mapActor : _mapRepresentedActors)
   {
      if (mapActor.Get())
      {
         if (const FTATMapSpriteEntry* spriteEntry = mapActor->GetCurrentMapSpriteEntry())
         {
            if (spriteEntry->Tag == spriteTag)
            {
               mapActorsToRemove.Add(mapActor.Get());
            }
         }
      }
   }

   for (UTATMapActorComponent* mapActorToRemove : mapActorsToRemove)
   {
      UnregisterMapActor(mapActorToRemove);
   }
}

bool UTATWorldMapSubsystem::IsMapActorRegistered(UTATMapActorComponent* mapActorComponent) const
{
   check(IsValid(mapActorComponent));
   return _mapRepresentedActors.Contains(mapActorComponent);
}

void UTATWorldMapSubsystem::BroadcastMapActorChange(const UTATMapActorComponent* mapActorComponent)
{
   check(IsValid(mapActorComponent));
   OnMapActorChanged.Broadcast(mapActorComponent);
}

FVector2D UTATWorldMapSubsystem::ConvertWorldLocationToMapLocation(const UObject* contextObject, const FVector& worldLocation, const FTATMapRepresentationData& mapRepresentationData, const FVector2D& mapImageSize, const FVector2D& mapOffset)
{
   if (!IsValid(contextObject))
   {
      UE_LOG(LogTATWorldMapSubsystem, Error, TEXT("ConvertWorldLocationToMapLocation() | contextObject is null!"));
      return FVector2D::Zero();
   }

   UWorld* world = GEngine->GetWorldFromContextObject(contextObject, EGetWorldErrorMode::ReturnNull);
   if (world == nullptr)
   {
      UE_LOG(LogTATWorldMapSubsystem, Error, TEXT("ConvertWorldLocationToMapLocation() | world is null!"));
      return FVector2D::Zero();
   }

   UTATWorldMapSubsystem* worldMapSubsystem = world->GetSubsystem<UTATWorldMapSubsystem>();
   if (worldMapSubsystem == nullptr)
   {
      UE_LOG(LogTATWorldMapSubsystem, Error, TEXT("ConvertWorldLocationToMapLocation() | worldMapSubsystem is null!"));
      return FVector2D::Zero();
   }

   // Get map boundary actor
   const ATATWorldMapBoundary* worldMapBoundary = worldMapSubsystem->_GetCurrentWorldMapBoundaryActor();
   if (!IsValid(worldMapBoundary))
   {
      const TCHAR* extraInfo = ATATWorldSettings::Get(contextObject).WorldMapBoundary ? TEXT("") : TEXT(" (one was not defined in TATWorldSettings)");
      UE_LOG(LogTATWorldMapSubsystem, Error, TEXT("ConvertWorldLocationToMapLocation() | Unable to find any valid WorldMapBoundary actor%s! Could not return map location"), extraInfo);
      return FVector2D::Zero();
   }

   // Transform the input location to actor-space
   const FVector2D worldLocationMapActorSpace = FVector2D(worldMapBoundary->GetTransform().InverseTransformPosition(worldLocation));

   // Divide box extents (doubled, as they are half-lengths)
   const FBox mapBounds = worldMapBoundary->GetMapAreaBoundingBox();
   const FVector2D mapSize = FVector2D(mapBounds.GetSize()) / FVector2D(worldMapBoundary->GetActorScale3D());
   FVector2D normalizedLocation = worldLocationMapActorSpace / mapSize;

   // Slide from [-0.5 <-> 0.5] to [0 <-> 1]
   normalizedLocation += FVector2D(0.5, 0.5);

   // Apply map image size and offset
   FVector2D mapLocation = mapOffset + (normalizedLocation * mapImageSize);

   if (mapRepresentationData.ShowGeneralAreaOnQuestLootObtained && mapRepresentationData.IsGeneralArea)
   {
      // The radius (GeneralAreaOffset) is in slate units, so to properly scale it we need to double the mapImageSize
      // This is likely magic wishy washy math but it works...
      // We should revisit this at a later date when we change Radius from slate units to world units
      const FVector2D generalAreaOffset = (mapRepresentationData.GeneralAreaOffset / mapImageSize * 2) * mapSize;
      mapLocation += generalAreaOffset;
   }
   return mapLocation;
}

float UTATWorldMapSubsystem::ConvertMapDistanceToSlateDistance(const UObject* contextObject, float mapDistance, const FVector2D& mapDimensions)
{
   if (!IsValid(contextObject))
   {
      UE_LOG(LogTATWorldMapSubsystem, Error, TEXT("ConvertMapDistanceToSlateDistance() | contextObject is null!"));
      return 0.0f;
   }

   UWorld* world = GEngine->GetWorldFromContextObject(contextObject, EGetWorldErrorMode::ReturnNull);
   if (world == nullptr)
   {
      UE_LOG(LogTATWorldMapSubsystem, Error, TEXT("ConvertMapDistanceToSlateDistance() | world is null!"));
      return 0.0f;
   }

   UTATWorldMapSubsystem* worldMapSubsystem = world->GetSubsystem<UTATWorldMapSubsystem>();
   if (worldMapSubsystem == nullptr)
   {
      UE_LOG(LogTATWorldMapSubsystem, Error, TEXT("ConvertMapDistanceToSlateDistance() | worldMapSubsystem is null!"));
      return 0.0f;
   }

   // Get map boundary actor
   const ATATWorldMapBoundary* worldMapBoundary = worldMapSubsystem->_GetCurrentWorldMapBoundaryActor();
   if (!IsValid(worldMapBoundary))
   {
      const TCHAR* extraInfo = ATATWorldSettings::Get(contextObject).WorldMapBoundary ? TEXT("") : TEXT(" (one was not defined in TATWorldSettings)");
      UE_LOG(LogTATWorldMapSubsystem, Error, TEXT("ConvertMapDistanceToSlateDistance() | Unable to find any valid WorldMapBoundary actor%s! Could not return map location"), extraInfo);
      return 0.0f;
   }

   // This is DEFINITELY magic wishy washy math but it works...
   // We should revisit this at a later date when we change all our measurements from slate units to world units
   const FVector2D boxExtents = worldMapBoundary->GetUnscaledBoundaryExtents() * 2;
   float mapSize = mapDimensions.Length();
   float boxSize = boxExtents.Length();
   const float convertedValue = mapDistance * (mapSize / boxSize / 3);
   return convertedValue;
}

void UTATWorldMapSubsystem::RegisterMapBoundary(ATATWorldMapBoundary* mapBoundaryActor)
{
   if (mapBoundaryActor == nullptr)
   {
      return;
   }

   auto getMapLabel = [](ATATWorldMapBoundary* mapBoundary) -> FText
   {
      check(mapBoundary != nullptr);
      if (!mapBoundary->MapLabel.IsEmptyOrWhitespace())
      {
         return mapBoundary->MapLabel;
      }
#if WITH_EDITOR
      return FText::FromString(FString::Printf(TEXT("MAP LABEL MISSING: %s"), *mapBoundary->GetName()));
#else
      return FText::FromString(TEXT("MAP LABEL MISSING"));
#endif
   };

   _registeredMaps.Add(FRegisteredMap{
      .BoundaryActor = mapBoundaryActor,
      .Bounds = mapBoundaryActor->GetMapAreaBoundingBox(),
      .Label = getMapLabel(mapBoundaryActor),
      .IsPrimary = mapBoundaryActor->MapType == ETATWorldMapBoundaryType::Primary,
   });
   
   _registeredMaps.Sort([](const FRegisteredMap& a, const FRegisteredMap& b)
   {
      if (a.IsPrimary && b.IsPrimary == false) return true;
      return a.Bounds.GetCenter().Z > b.Bounds.GetCenter().Z;
   });

   for (int i = 0; i < _registeredMaps.Num(); i++)
   {
      if (_registeredMaps[i].IsPrimary)
      {
         _primaryMapIndex = i;
         break;
      }
   }
}

