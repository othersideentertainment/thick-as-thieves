FVector ATATPowerLine::GetPowerLineWorldLocation(float normalizedLocation) const
{
   check(SplineComponent != nullptr);
   if (SplineComponent->GetNumberOfSplinePoints() < 2)
   {
      return GetActorLocation();
   }
   const float splineDistance = FMath::Clamp(normalizedLocation, 0.0f, 1.0f) * SplineComponent->GetSplineLength();
   return SplineComponent->GetLocationAtDistanceAlongSpline(splineDistance, ESplineCoordinateSpace::World);
}

float ATATPowerLine::GetPowerLineLength() const
{
   check(SplineComponent != nullptr);
   if (SplineComponent->GetNumberOfSplinePoints() < 2)
   {
      return 0.0f;
   }
   return SplineComponent->GetSplineLength();
}

bool ATATPowerLine::FindSplineInputKeyForCharacterOnPowerLine(ACharacter* character, float& splineInputKey) const
{
   if (character == nullptr)
   {
      splineInputKey = 0.0f;
      return false;
   }

   splineInputKey = SplineComponent->FindInputKeyClosestToWorldLocation(character->GetActorLocation());
   return _charactersOnPowerLine.Contains(character);
}

void ATATPowerLine::_AddPowerLineGameplayTags(ACharacter* character)
{
   if (StandingOnPowerLineGameplayTag.IsValid())
   {
      if (UAbilitySystemComponent* asc = UAbilitySystemGlobals::GetAbilitySystemComponentFromActor(character))
      {
         asc->AddLooseGameplayTag(StandingOnPowerLineGameplayTag);
      }
   }
}

void ATATPowerLine::_RemovePowerLineGameplayTags(ACharacter* character)
{
   if (StandingOnPowerLineGameplayTag.IsValid())
   {
      if (UAbilitySystemComponent* asc = UAbilitySystemGlobals::GetAbilitySystemComponentFromActor(character))
      {
         asc->RemoveLooseGameplayTag(StandingOnPowerLineGameplayTag);
      }
   }
}

void ATATPowerLine::_StartPowerSurge(ACharacter* character)
{
   if (character == nullptr || _charactersAffectedByPowerSurge.Contains(character))
   {
      return;
   }

   _charactersAffectedByPowerSurge.Add(character);

   if (HasAuthority() && PowerSurgeGameplayEffect)
   {
      _AuthorityApplyPowerSurge(character);
   }
}

void ATATPowerLine::_EndPowerSurge(ACharacter* character)
{
   if (character == nullptr || !_charactersAffectedByPowerSurge.Contains(character))
   {
      return;
   }

   if (HasAuthority() && PowerSurgeGameplayEffect)
   {
      _AuthorityRemovePowerSurge(character);
   }

   _charactersAffectedByPowerSurge.Remove(character);
}

void ATATPowerLine::_AuthorityApplyPowerSurge(ACharacter* character)
{
   check(HasAuthority());
   if (character == nullptr || !PowerSurgeGameplayEffect)
   {
      return;
   }

   UAbilitySystemComponent* asc = UAbilitySystemGlobals::GetAbilitySystemComponentFromActor(character);
   if (asc == nullptr)
   {
      return;
   }

   FActiveGameplayEffectHandle* existingHandle = _powerSurgeEffectHandles.Find(character);
   if (existingHandle != nullptr && asc->GetActiveGameplayEffect(*existingHandle) != nullptr)
   {
      // We already have an active effect
      return;
   }

   const float splineInputKey = SplineComponent->FindInputKeyClosestToWorldLocation(character->GetActorLocation());
   const FVector splineLocation = SplineComponent->GetLocationAtSplineInputKey(splineInputKey, ESplineCoordinateSpace::World);
   const FVector splineRightVector = SplineComponent->GetRightVectorAtSplineInputKey(splineInputKey, ESplineCoordinateSpace::World);

   auto pointOnTraceLine = [&](float distance) -> FVector
   {
      return splineLocation + (FVector::UpVector * 50.0f) - (splineRightVector * distance);
   };

   FHitResult fakeHitResult{};
   fakeHitResult.Init();
   fakeHitResult.bBlockingHit = true;
   fakeHitResult.TraceStart = pointOnTraceLine(300.0f);
   fakeHitResult.TraceEnd = pointOnTraceLine(-300.0f);
   fakeHitResult.Location = pointOnTraceLine(30.0f);
   fakeHitResult.ImpactPoint = fakeHitResult.Location;
   fakeHitResult.HitObjectHandle = FActorInstanceHandle(character);
   fakeHitResult.Component = TWeakObjectPtr<UPrimitiveComponent>(character->GetCapsuleComponent());
   fakeHitResult.Distance = FVector::Distance(fakeHitResult.TraceStart, fakeHitResult.Location);
   fakeHitResult.Time = fakeHitResult.Distance / FVector::Distance(fakeHitResult.TraceStart, fakeHitResult.TraceEnd);
   fakeHitResult.Normal = (fakeHitResult.Location - fakeHitResult.TraceStart).GetSafeNormal();
   fakeHitResult.ImpactNormal = fakeHitResult.Normal;

   FGameplayEffectContextHandle effectContext = asc->MakeEffectContext();
   effectContext.AddOrigin(fakeHitResult.Location);
   effectContext.AddHitResult(fakeHitResult);
   effectContext.AddSourceObject(this);
   FActiveGameplayEffectHandle effectHandle = asc->ApplyGameplayEffectToSelf(PowerSurgeGameplayEffect.GetDefaultObject(), 0.0f, effectContext, FPredictionKey());
   if (effectHandle.IsValid())
   {
      _powerSurgeEffectHandles.Add(character, effectHandle);
   }
}

void ATATPowerLine::_AuthorityRemovePowerSurge(ACharacter* character)
{
   check(HasAuthority());
   if (character == nullptr || !PowerSurgeGameplayEffect)
   {
      return;
   }

   UAbilitySystemComponent* asc = UAbilitySystemGlobals::GetAbilitySystemComponentFromActor(character);
   if (asc == nullptr)
   {
      return;
   }

   FActiveGameplayEffectHandle* effectHandle = _powerSurgeEffectHandles.Find(character);
   if (effectHandle == nullptr)
   {
      return;
   }

   asc->RemoveActiveGameplayEffect(*effectHandle, PowerSurgeGameplayEffectStacksToRemove);
   _powerSurgeEffectHandles.Remove(character);
}

void ATATPowerLine::_OnPowerSurgeChanged(bool powerSurgeEnabled)
{
   if (powerSurgeEnabled)
   {
      for (ACharacter* character : _charactersOnPowerLine)
      {
         _StartPowerSurge(character);
      }
   }
   else
   {
      for (ACharacter* character : _charactersOnPowerLine)
      {
         _EndPowerSurge(character);
      }
   }
}
